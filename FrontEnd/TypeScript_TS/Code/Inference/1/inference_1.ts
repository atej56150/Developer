// Implicit Types
let a = "This was a string";
a = "yep its a string"
console.log(a)

let b = "This was a string";
b = 1
console.log(b)

// Explicit Types
let c: string = "its a string";
let d: number = 1;
c = true;
d = 2
console.log(c)
console.log(d)

